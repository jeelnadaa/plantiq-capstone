    for block in (retr, prompt):
        assert "p.step" not in block.replace('was: with p.step("Retrieval")', ""), "unexpected pipeline step"
    sub = lambda s: s.replace("inp.message", "inp_message").replace("inp.attached_image_name", "attached_image_name")
