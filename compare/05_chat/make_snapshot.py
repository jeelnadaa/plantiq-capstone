"""Regenerates plantiq_chat_snapshot/ from the backend source (read-only), so the benchmark never imports the app.

chat.py: the backend's constants (weather words and matcher, coordinate regexes, system prompt, helpers), `_scan_block`,
the retrieval block and the prompt block are sliced verbatim out of backend/app/services/chat.py; only the database
work of `process_message` is left out (`build_turn`). knowledge.py and lang_router.py are copied (imports adjusted).
Afterwards run verify_snapshot.py with the backend's environment to prove the prompts are identical.

Run:  .venv\\Scripts\\python 05_chat\\make_snapshot.py
"""
