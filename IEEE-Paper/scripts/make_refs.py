"""Regenerates refs_main.tex and refs_short.tex, the reference lists the papers \\input.

BibTeX with IEEEtran.bst writes page ranges as "770--778", which prints an en dash. This script builds each paper once
with BibTeX (wrapper defines \\plantiqusebibtex), takes the generated .bbl and writes it with plain hyphens in page
ranges. Run it after changing references.bib or the order of the first citations.

    python scripts/make_refs.py        (from IEEE-Paper/)
"""
import re
import subprocess
from pathlib import Path

D = Path(__file__).resolve().parents[1]
TECTONIC = D / "tools" / "tectonic.exe"

for content, wrapper_class, out in (("paper_content", "conference,12pt", "refs_main.tex"),
                                    ("short_content", "conference,12pt", "refs_short.tex")):
    tmp = D / f"_refs_{content}.tex"
    tmp.write_text("\\documentclass[%s]{IEEEtran}\n\\def\\plantiqusebibtex{}\n\\input{%s}\n" % (wrapper_class, content),
                   encoding="utf-8")
    subprocess.run([str(TECTONIC), "--keep-intermediates", tmp.name], cwd=D, check=True, capture_output=True)
    bbl = (D / f"_refs_{content}.bbl").read_text(encoding="utf-8")
    bbl = re.sub(r"(\d)--(\d)", r"\1-\2", bbl)       # page ranges: en dash -> hyphen
    assert "--" not in bbl.split("\\begin{thebibliography}", 1)[1], "unexpected -- left in the bibliography"
    (D / out).write_text("% Generated by scripts/make_refs.py from references.bib; do not edit by hand.\n" + bbl,
                         encoding="utf-8")
    for f in D.glob(f"_refs_{content}.*"):
        f.unlink()
    print("wrote", out)
