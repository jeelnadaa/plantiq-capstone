    retr = src[src.index("        docs: list[dict] = []"):src.index("        lang_rule = (")]
    retr = retr.replace('            with p.step("Retrieval"):\n', '            if True:  # was: with p.step("Retrieval"):\n')
    prompt = src[src.index("        lang_rule = ("):src.index('{weather_rule}"""') + len('{weather_rule}"""')]
    route = src[src.index("            route = route_query("):].split("\n", 1)[0].strip()
    offline = src[src.index("offline_chat_reply("):].split("\n", 1)[0]
