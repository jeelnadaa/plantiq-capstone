import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SRC = REPO / "backend" / "app" / "services"
OUT = HERE / "plantiq_chat_snapshot"


def commit() -> str:
    return subprocess.run(["git", "-C", str(REPO), "log", "-1", "--format=%h", "--", "backend/app/services"],
                          capture_output=True, text=True).stdout.strip() or "working tree"


def dedent4(block: str) -> str:
    """The sliced blocks sit inside `with Pipeline(...)` (8 spaces); build_turn's body is at 4. Prompt text lines
    inside the f-string start at column 0 and are left untouched."""
    return "\n".join(line[4:] if line.startswith("        ") else line for line in block.split("\n"))


